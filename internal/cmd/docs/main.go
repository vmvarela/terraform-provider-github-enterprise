// Command docs generates Registry documentation from the protocol schema and
// checked-in examples. It does not configure a provider or contact GitHub.
package main

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/hashicorp/terraform-plugin-framework/providerserver"
	"github.com/hashicorp/terraform-plugin-go/tfprotov6"
	"github.com/vmvarela/terraform-provider-github-enterprise/internal/provider"
)

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
func generate() error {
	s := providerserver.NewProtocol6(provider.New("docs")())()
	r, err := s.GetProviderSchema(context.Background(), &tfprotov6.GetProviderSchemaRequest{})
	if err != nil {
		return err
	}
	for _, d := range r.Diagnostics {
		if d.Severity == tfprotov6.DiagnosticSeverityError {
			return fmt.Errorf("%s: %s", d.Summary, d.Detail)
		}
	}
	if err := writeDoc("GitHub Enterprise Provider", "docs/index.md", "examples/provider/provider.tf", r.Provider, ""); err != nil {
		return err
	}
	for kind, schemas := range map[string]map[string]*tfprotov6.Schema{"resources": r.ResourceSchemas, "data-sources": r.DataSourceSchemas} {
		for name, schema := range schemas {
			short := strings.TrimPrefix(name, "github_enterprise_")
			base := filepath.Join("examples", kind, short)
			importText := ""
			if kind == "resources" {
				b, err := os.ReadFile(filepath.Join(base, "import.sh")) // #nosec G304 -- Paths come from compiled-in provider schema names, not user input.
				if err != nil {
					return err
				}
				importText = string(b)
			}
			label := "Data Source"
			if kind == "resources" {
				label = "Resource"
			}
			if err := writeDoc(name+" ("+label+")", filepath.Join("docs", kind, short+".md"), filepath.Join(base, "main.tf"), schema, importText); err != nil {
				return err
			}
		}
	}
	return nil
}
func writeDoc(title, path, example string, schema *tfprotov6.Schema, importText string) error {
	b, err := os.ReadFile(example) // #nosec G304 -- Callers use fixed paths or compiled-in provider schema names, not user input.
	if err != nil {
		return err
	}
	var out strings.Builder
	fmt.Fprintf(&out, "---\npage_title: %q\ndescription: |-\n  %s\n---\n\n", title, schema.Block.Description)
	fmt.Fprintf(&out, "<!-- Generated by go run ./internal/cmd/docs. Edit schema descriptions or examples. -->\n\n# %s\n\n%s\n\n", title, schema.Block.Description)
	fmt.Fprintf(&out, "## Example\n\n```hcl\n%s```\n\n", string(b))
	fmt.Fprintln(&out, "## Schema\n\n| Attribute | Type | Requirement | Description |\n| --- | --- | --- | --- |")
	attrs := append([]*tfprotov6.SchemaAttribute(nil), schema.Block.Attributes...)
	sort.Slice(attrs, func(i, j int) bool { return attrs[i].Name < attrs[j].Name })
	for _, a := range attrs {
		req := "Read-only"
		if a.Required {
			req = "Required"
		} else if a.Optional {
			req = "Optional"
		}
		typ := "object"
		if a.Type != nil {
			// Terraform type names are user-facing: render Set[tftypes.String] as Set of String.
			typ = strings.NewReplacer("tftypes.", "", "[", " of ", "]", "").Replace(a.Type.String())
		}
		if a.NestedType != nil {
			typ = "list(object)"
		}
		fmt.Fprintf(&out, "| `%s` | `%s` | %s | %s |\n", a.Name, typ, req, strings.ReplaceAll(a.Description, "|", "\\|"))
	}
	if title == "github_enterprise_teams (Data Source)" {
		fmt.Fprintln(&out, "\nEach team object contains `team_id`, `name`, `slug`, `description`, `group_id`, and `organization_selection_type`.")
	}
	if importText != "" {
		fmt.Fprintf(&out, "\n## Import\n\n```sh\n%s```\n", importText)
	}
	fmt.Fprintln(&out, "\nSee the [provider guide](https://github.com/vmvarela/terraform-provider-github-enterprise#authentication) for authentication, ownership and compatibility requirements.")
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil { // #nosec G301 -- Generated public Registry docs must be readable; these directories contain no secrets.
		return err
	}
	return os.WriteFile(path, []byte(out.String()), 0644) // #nosec G306 -- Generated public Registry docs must be readable and contain no secrets.
}
